"""Email delivery with a development sink and SMTP backends."""

from __future__ import annotations

import re
import smtplib
import uuid
from datetime import UTC, datetime
from email.message import EmailMessage
from email.utils import formataddr
from pathlib import Path

from app.config.settings import settings
from app.core.errors import IntegrationError
from app.core.logging import get_logger

logger = get_logger(__name__)

_SAFE = re.compile(r"[^a-zA-Z0-9_.-]+")


def send_email(*, to: str, subject: str, body: str, html: str | None = None) -> dict[str, str]:
    """Send an email. Returns metadata about where it was delivered.

    The sink backend writes a real .eml file and an .html preview into EMAIL_SINK_DIR so
    demo environments can inspect messages without an SMTP server.
    """
    message = EmailMessage()
    message["From"] = formataddr(("RESOLVE", settings.EMAIL_FROM))
    message["To"] = to
    message["Subject"] = subject
    message["Date"] = datetime.now(UTC).strftime("%a, %d %b %Y %H:%M:%S +0000")
    message["Message-ID"] = f"<{uuid.uuid4().hex}@resolve.local>"
    message.set_content(body)
    if html:
        message.add_alternative(html, subtype="html")

    if settings.EMAIL_BACKEND == "sink":
        directory = Path(settings.EMAIL_SINK_DIR)
        directory.mkdir(parents=True, exist_ok=True)
        stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%S%fZ")
        safe_to = _SAFE.sub("_", to)[:60]
        path = directory / f"{stamp}-{safe_to}.eml"
        path.write_bytes(bytes(message))
        logger.info("email_sink_written", path=str(path), to=to, subject=subject)
        return {"backend": "sink", "path": str(path), "message_id": message["Message-ID"]}

    if settings.EMAIL_BACKEND == "smtp":
        try:
            with smtplib.SMTP(settings.SMTP_HOST, settings.SMTP_PORT, timeout=15) as smtp:
                if settings.SMTP_TLS:
                    smtp.starttls()
                if settings.SMTP_USER:
                    smtp.login(settings.SMTP_USER, settings.SMTP_PASSWORD)
                smtp.send_message(message)
        except (OSError, smtplib.SMTPException) as exc:
            raise IntegrationError(f"SMTP delivery failed: {exc}", code="email_delivery_failed") from exc
        return {"backend": "smtp", "message_id": message["Message-ID"]}

    raise IntegrationError(f"Unsupported email backend: {settings.EMAIL_BACKEND}")


def build_case_notification_email(*, recipient_name: str, title: str, body: str, link: str) -> tuple[str, str]:
    subject = f"[RESOLVE] {title}"
    html = (
        f"<div style='font-family:Segoe UI,Arial,sans-serif;color:#14161a'>"
        f"<h2 style='font-size:18px'>{title}</h2><p>{body}</p>"
        f"<p><a href='{link}' style='color:#146c4f'>Open in RESOLVE</a></p>"
        "<p style='color:#6b7076;font-size:12px'>Generated by RESOLVE. Do not reply directly.</p></div>"
    )
    return subject, html
